#!/usr/bin/env node
// Generates backend/src/generated/ttsRegistry.json from the TTS registry (registry/ in the realtime-tts repo): per engine, its
// hardware and price class, plus the registry hash. realtimeTtsBilling.ts reads it to decide which price class an engine id the
// backend does not know by name is billed at (cpu -> live, anything else -> studio). Money depends on it, so it is generated, not typed.
//
//   node scripts/sync-tts-registry.mjs --registry <path to the registry folder, the one holding dist/>
//   node scripts/sync-tts-registry.mjs --registry <path> --check     (exit 1 if the generated file is stale; run it in CI)
//   TTS_REGISTRY_DIR=<path> node scripts/sync-tts-registry.mjs [--check]
//
// Run it (and commit the result) BEFORE a new engine is enabled on the gateway. Fails, writing nothing, if the registry has a price
// class the backend has no ratio for, or one that disagrees with the engine's hardware (cpu -> live, gpu -> studio): changing either
// is a price decision, not a registry edit. No dependencies.
import { readFileSync, writeFileSync, mkdirSync, existsSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const HERE = dirname(fileURLToPath(import.meta.url))
const OUT = join(HERE, '../src/generated/ttsRegistry.json')
const PRICE_CLASSES = ['live', 'studio'] // keep equal to PRICE_CLASS_RATIO in src/lib/realtimeTtsBilling.ts
const CLASS_FOR_HARDWARE = { cpu: 'live', gpu: 'studio' }

const fail = (m) => { throw new Error(`sync-tts-registry: ${m}`) }

export function build(registryDir) {
  const p = join(registryDir, 'dist/registry.json')
  if (!existsSync(p)) fail(`missing ${p}`)
  const reg = JSON.parse(readFileSync(p, 'utf8'))
  if (!reg.hash || !reg.engines || typeof reg.engines !== 'object') fail('dist/registry.json lacks hash/engines (rebuild the registry)')
  const engines = {}
  for (const [id, e] of Object.entries(reg.engines)) {
    if (!['cpu', 'gpu'].includes(e.hardware)) fail(`engine ${id}: hardware must be cpu or gpu, got ${JSON.stringify(e.hardware)}`)
    if (!PRICE_CLASSES.includes(e.price_class)) fail(`engine ${id}: price_class ${JSON.stringify(e.price_class)} has no ratio in realtimeTtsBilling.ts (add one deliberately, with the owner's price decision)`)
    if (CLASS_FOR_HARDWARE[e.hardware] !== e.price_class) fail(`engine ${id}: price_class ${e.price_class} disagrees with hardware ${e.hardware} (billing classes unknown engines by hardware); settle the price before syncing`)
    engines[id] = { public_alias: e.public_alias ?? null, hardware: e.hardware, price_class: e.price_class }
  }
  if (Object.keys(engines).length === 0) fail('the registry has no engines')
  return {
    _generated: 'GENERATED by backend/scripts/sync-tts-registry.mjs from the TTS registry (registry/dist). Do not edit by hand; run: node scripts/sync-tts-registry.mjs --registry <registry dir>',
    registry: { version: reg.version, hash: reg.hash },
    engines,
  }
}

function main() {
  const argv = process.argv.slice(2)
  const ri = argv.indexOf('--registry')
  const dir = ri !== -1 ? argv[ri + 1] : process.env.TTS_REGISTRY_DIR
  if (!dir) fail('pass --registry <registry dir> or set TTS_REGISTRY_DIR')
  const out = `${JSON.stringify(build(resolve(dir)), null, 2)}\n`
  const cur = existsSync(OUT) ? readFileSync(OUT, 'utf8') : null
  if (argv.includes('--check')) {
    if (cur !== out) { console.error(`stale (run the sync): ${OUT}`); process.exit(1) }
    console.log('up to date')
    return
  }
  mkdirSync(dirname(OUT), { recursive: true })
  writeFileSync(OUT, out)
  console.log(`wrote ${OUT}`)
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  try { main() } catch (e) { console.error(e.message); process.exit(1) }
}
